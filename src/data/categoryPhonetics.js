export function categoryPhonetic(word) {
  const ipa = CATEGORY_PHONETICS[String(word || '').trim().toLowerCase()];
  return ipa ? `/${ipa}/` : '';
}

// Fill previously imported cards without changing their SRS state or personal edits.
export function fillCategoryPhonetics(words) {
  return words.map((word) => {
    if (word.phonetic?.trim()) return word;
    const phonetic = categoryPhonetic(word.word);
    return phonetic ? { ...word, phonetic } : word;
  });
}
